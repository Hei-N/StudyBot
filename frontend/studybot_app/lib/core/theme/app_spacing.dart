/// The spacing scale used everywhere in the app. Values are a 4pt-based
/// scale — pick the nearest token rather than an arbitrary number so
/// spacing stays visually consistent across every screen.
abstract final class AppSpacing {
  static const xxs = 4.0;
  static const xs = 8.0;
  static const sm = 12.0;
  static const md = 16.0;
  static const lg = 24.0;
  static const xl = 32.0;
  static const xxl = 48.0;
}
